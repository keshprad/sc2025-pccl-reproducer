#!/bin/bash

# Expected environment file name set by caller
# Remove existing environment file if it exists
rm -f "$DS_ENV_FILE"

echo "WRKSPC=$WRKSPC" >> "$DS_ENV_FILE"

# ROCm environment variables for DeepSpeed on Frontier
echo "ROCM_PATH=$ROCM_PATH" >> "$DS_ENV_FILE"
echo "HIP_PATH=$HIP_PATH" >> "$DS_ENV_FILE"
echo "ROCM_HOME=$ROCM_HOME" >> "$DS_ENV_FILE"

# Set proper compiler for CPU extensions (needs GCC 9+ compatibility)
echo "CXX=$CXX" >> "$DS_ENV_FILE"
echo "CC=$CC" >> "$DS_ENV_FILE"
echo "CPP=$CPP" >> "$DS_ENV_FILE"

## calculating the number of nodes and GPUs
echo "NNODES=$NNODES" >> "$DS_ENV_FILE"
echo "GPUS_PER_NODE=$GPUS_PER_NODE" >> "$DS_ENV_FILE"
echo "GPUS=$GPUS" >> "$DS_ENV_FILE"

echo "MASTER_ADDR=$MASTER_ADDR" >> "$DS_ENV_FILE"
echo "MASTER_PORT=$MASTER_PORT" >> "$DS_ENV_FILE"
echo "NCCL_SOCKET_IFNAME=$NCCL_SOCKET_IFNAME" >> "$DS_ENV_FILE"
echo "WORLD_SIZE=$WORLD_SIZE" >> "$DS_ENV_FILE"

## some RCCL env variables
echo "HSA_FORCE_FINE_GRAIN_PCIE=$HSA_FORCE_FINE_GRAIN_PCIE" >> "$DS_ENV_FILE"
echo "NCCL_CROSS_NIC=$NCCL_CROSS_NIC" >> "$DS_ENV_FILE"
echo "CUDA_DEVICE_MAX_CONNECTIONS=$CUDA_DEVICE_MAX_CONNECTIONS" >> "$DS_ENV_FILE"
echo "NCCL_NET_GDR_LEVEL=$NCCL_NET_GDR_LEVEL" >> "$DS_ENV_FILE"
# Additional NCCL settings for multi-node
echo "NCCL_IB_DISABLE=$NCCL_IB_DISABLE" >> "$DS_ENV_FILE"
# echo "NCCL_DEBUG=$NCCL_DEBUG" >> "$DS_ENV_FILE"
echo "NCCL_TREE_THRESHOLD=$NCCL_TREE_THRESHOLD" >> "$DS_ENV_FILE"
## RCCL plugin
echo "LD_LIBRARY_PATH=$LD_LIBRARY_PATH" >> "$DS_ENV_FILE"

# mpich gpu support
echo "MPICH_GPU_SUPPORT_ENABLED=$MPICH_GPU_SUPPORT_ENABLED" >> "$DS_ENV_FILE"
echo "MPICH_OFI_VERBOSE=$MPICH_OFI_VERBOSE" >> "$DS_ENV_FILE"
echo "MPICH_OFI_NIC_POLICY=$MPICH_OFI_NIC_POLICY" >> "$DS_ENV_FILE"
echo "MPICH_OFI_NIC_MAPPING=$MPICH_OFI_NIC_MAPPING" >> "$DS_ENV_FILE"

# fi variables
echo "FI_CXI_RDZV_THRESHOLD=$FI_CXI_RDZV_THRESHOLD" >> "$DS_ENV_FILE"
echo "FI_CXI_RDZV_GET_MIN=$FI_CXI_RDZV_GET_MIN" >> "$DS_ENV_FILE"
echo "FI_CXI_RDZV_EAGER_SIZE=$FI_CXI_RDZV_EAGER_SIZE" >> "$DS_ENV_FILE"
echo "MPICH_OFI_CXI_COUNTER_VERBOSE=$MPICH_OFI_CXI_COUNTER_VERBOSE" >> "$DS_ENV_FILE"
# collecting counter data
echo "MPICH_OFI_CXI_COUNTER_REPORT=$MPICH_OFI_CXI_COUNTER_REPORT" >> "$DS_ENV_FILE"
echo "HSA_ENABLE_SDMA=$HSA_ENABLE_SDMA" >> "$DS_ENV_FILE"
